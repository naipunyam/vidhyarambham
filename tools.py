FEEDBACK_SCRIPT = """CONSTRUCTIVE FEEDBACK SCRIPT (SBI + request; say it in private)
Ask:        "Can I share one thing I noticed? It might help with ______."
Situation:  "On (day), at (place / meeting)..."
Behaviour:  "...I noticed you (what you saw or heard, no labels)..."
Impact:     "...and the effect was (on the work, on others, on me)."
Their view: "How did it look from your side?"  (then LISTEN)
Request:    "Next time, could you ______?" or "What would help?"
Close:      "Thanks for hearing me out. I value (something true)."
Avoid: "always", "never", "you are lazy/careless", feedback in front of others."""

