CONVERSATION_LOG = """CONVERSATION LOG (one line per conversation)
Date | Who (name, how we met) | Listening-first? (Y/N) | Follow-up questions asked | One thing I learned about them | Name remembered next time? | Next contact
Daily challenge rotation (pick one a day):
- Listen first: let them talk 2/3 of the time; summarise before you reply.
- Two follow-ups: ask two questions about what they just said.
- Names: use their name once in the talk; write it down within an hour.
- Genuine praise: one specific, true compliment about effort or a choice."""

