BIAS_JOURNAL = """BIAS JOURNAL (2 weeks, 3 entries a day: me, the news, an ad)
Date | Where (me / news / ad) | What happened (one line) | Bias or distortion | Evidence it was that | Better thinking
Example: 12 Nov | me | Kept reading a boring PSC guide because I paid Rs 400 | sunk cost | The money is gone either way | Switch to the free SCERT text for this topic
Example: 12 Nov | news | "Third accident on this road this week: roads unsafe" | availability | No yearly figures given | Look for the yearly accident count before deciding
Example: 12 Nov | ad | "Was Rs 2,999, now Rs 999, only today!" | anchoring + scarcity | The "was" price is the advertiser's own | Compare with two other shops
Biases to look for: confirmation, sunk cost, overconfidence, planning fallacy,
loss aversion, anchoring, availability, halo effect, fundamental attribution
error, social proof, plus the CBT distortions (PD-M03-L02).
At the end of each week: count which bias you caught most often in yourself."""

