MANIPULATION_CHECK = """MANIPULATION RED-FLAG CHECK (use on any ad, message, call or pitch)
[ ] Urgency: "only today", "act now", countdown timers
[ ] Secrecy: "don't tell anyone", "don't discuss with family"
[ ] Authority without proof: police, CBI, bank, RBI, "senior manager", uniforms on video
[ ] Too good to be true: guaranteed returns, prizes you did not enter for
[ ] Fear: arrest, account blocked, illness, "your son is in trouble"
[ ] Payment pressure: UPI collect request, gift cards, crypto, "processing fee"
[ ] Recruitment focus: money comes from bringing in others (MLM)
[ ] Love or guilt used as leverage: "if you loved me you would..."
[ ] Your memory questioned: "that never happened, you're imagining it"
[ ] Design tricks: pre-ticked boxes, hidden charges, hard-to-cancel plans
Two or more ticks: STOP. Do not pay, click or share OTPs. Hang up, verify
through an official number you look up yourself, talk to someone you trust.
Money already lost to cyber fraud: call 1930 immediately."""

